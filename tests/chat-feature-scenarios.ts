import assert from "node:assert/strict";
import { v7 } from "uuid";
import { sql } from "drizzle-orm";
import { db } from "../apps/api/src/db";
import { publishActivity } from "../apps/api/src/modules/chat/activity";
type Call=(path:string,method?:string,body?:unknown,cookie?:string)=>Promise<Response>;
export async function chatFeatureScenarios(ids:string[],cookies:string[],chatId:string,groupId:string,call:Call){
  const [admin,one,two]=cookies;
  const query=(value:string,extra="")=>`search?query=${encodeURIComponent(value)}${extra}`;
  const text="Ёлочное приглашение для встречи @Test 2";
  const mention={userId:ids[2],start:text.indexOf("@"),length:7};
  const response=await call(`chats/${chatId}/messages`,"POST",{clientMessageId:v7(),text:"  "+text,mentions:[{...mention,start:mention.start+2}]},one);
  assert.equal(response.status,200,await response.clone().text());const messageId=(await response.json()).id;
  const search=await(await call(query("елоч приглаш"),"GET",undefined,two)).json();
  assert.ok(search.messages.some((m:{id:string})=>m.id===messageId));
  assert.ok(search.messages.every((m:Record<string,unknown>)=>!("email" in m)));
  const forbidden=await(await call(query("елоч приглаш"),"GET",undefined,admin)).json();assert.equal(forbidden.messages.length,0);
  assert.equal((await call(query("елоч",`&chatId=${chatId}`),"GET",undefined,admin)).status,403);
  const author=await(await call(query("елоч",`&authorId=${ids[2]}`),"GET",undefined,two)).json();assert.equal(author.messages.length,0);
  const excluded=await(await call(query("елоч","&to=2000-01-01"),"GET",undefined,two)).json();assert.equal(excluded.messages.length,0);
  const injection=await call(query("'; DROP TABLE message; --"),"GET",undefined,two);assert.equal(injection.status,200);
  assert.equal((await call(query("е"),"GET",undefined,two)).status,400);
  assert.equal((await call(`chats/${chatId}/receipts`,"GET",undefined,admin)).status,403);
  let receipts=await(await call(`chats/${chatId}/receipts`,"GET",undefined,one)).json();
  const initial=receipts.find((r:{userId:string})=>r.userId===ids[2]);
  const around=await(await call(`chats/${chatId}/messages?aroundId=${messageId}`,"GET",undefined,two)).json();
  const found=around.messages.find((m:{id:string})=>m.id===messageId);
  assert.deepEqual(found.content.mentions,[mention]);
  assert.ok(initial.deliveredAt<found.createdAt);
  assert.equal((await call("receipts/delivered","POST",{items:[{chatId,messageId}]},two)).status,200);
  receipts=await(await call(`chats/${chatId}/receipts`,"GET",undefined,one)).json();
  assert.equal(receipts.find((r:{userId:string})=>r.userId===ids[2]).deliveredAt,found.createdAt,"retain microsecond precision");
  const beforeCount=Number((await db.execute(sql`select count(*) as n from outbox where kind='receipt.changed'`)).rows[0].n);
  await call("receipts/delivered","POST",{items:[{chatId,messageId}]},two);
  assert.equal(Number((await db.execute(sql`select count(*) as n from outbox where kind='receipt.changed'`)).rows[0].n),beforeCount,"repeated delivery must not create a refresh loop");
  assert.equal((await call(`chats/${chatId}/read`,"POST",{messageId},two)).status,200);
  receipts=await(await call(`chats/${chatId}/receipts`,"GET",undefined,one)).json();assert.equal(receipts.find((r:{userId:string})=>r.userId===ids[2]).readAt,found.createdAt);
  assert.equal((await call("receipts/delivered","POST",{items:[{chatId:groupId,messageId}]},two)).status,404);
  assert.equal((await call(`chats/${chatId}/messages`,"POST",{clientMessageId:v7(),text,mentions:[{...mention,userId:ids[0]}]},one)).status,400);
  assert.equal((await call(`chats/${chatId}/messages`,"POST",{clientMessageId:v7(),text,mentions:[{...mention,length:5}]},one)).status,400);
  assert.equal((await call(`messages/${messageId}`,"PATCH",{text,mentions:[mention]},one)).status,200);
  const headers=new Headers({cookie:two});
  await publishActivity(headers,{chatId,kind:"typing"},"test-device");
  await assert.rejects(publishActivity(new Headers({cookie:admin}),{chatId,kind:"typing"},"test-device"));
  await assert.rejects(publishActivity(headers,{chatId,kind:"invalid"},"test-device"));
  // Search pagination and around jumps stay bounded, including equal timestamps.
  const pageChat=await(await call("chats","POST",{kind:"group",title:"Search pagination",userIds:[ids[2]]},one)).json();
  for(let i=0;i<65;i++)await db.execute(sql`insert into message(chat_id,author_id,client_message_id,content,created_at) values(${pageChat.id},${ids[1]},${v7()},'{"text":"Пагинация поиска"}'::jsonb,'2026-01-01T00:00:00.123456Z')`);
  const first=await(await call(query("пагин",`&chatId=${pageChat.id}`),"GET",undefined,two)).json();
  assert.equal(first.messages.length,30);assert.ok(first.next);
  const second=await(await call(query("пагин",`&chatId=${pageChat.id}&beforeId=${first.next.id}&beforeAt=${encodeURIComponent(first.next.at)}`),"GET",undefined,two)).json();
  assert.equal(second.messages.length,30);assert.equal(new Set([...first.messages,...second.messages].map(m=>m.id)).size,60);
  const middle=first.messages[15];
  const window=await(await call(`chats/${pageChat.id}/messages?aroundId=${middle.id}`,"GET",undefined,two)).json();
  assert.ok(window.messages.some((m:{id:string})=>m.id===middle.id));assert.ok(window.messages.length<=100);
  await call(`chats/${pageChat.id}`,"PATCH",{remove:ids[2]},one);
  assert.equal((await call(query("пагин",`&chatId=${pageChat.id}`),"GET",undefined,two)).status,403);
  assert.equal((await call(`chats/${pageChat.id}/messages?aroundId=${middle.id}`,"GET",undefined,two)).status,403);
}
